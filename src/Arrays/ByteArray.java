package Arrays;
class ByteArray
{
    public static void main(String[] args)
    {
        byte[] age = {18, 20, 22, 24, 26};

        System.out.println(age[0]);
        System.out.println(age[1]);
        System.out.println(age[2]);
        System.out.println(age[3]);
        System.out.println(age[4]);
    }
}